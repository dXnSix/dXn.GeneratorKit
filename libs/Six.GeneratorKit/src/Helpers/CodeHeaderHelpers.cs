namespace Six.GeneratorKit;

/// <summary>
/// Helpers class for generating code headers.
/// </summary>
[PublicAPI]
[ExcludeFromCodeCoverage]
public static class CodeHeaderHelpers
{
  /// <summary>
  /// Generates a code header with the provided author name and URL.
  /// </summary>
  /// <remarks>
  /// Also adds the <c>nullable enable</c> directive.
  /// </remarks>
  /// <param name="authorName">The name of the author.</param>
  /// <param name="authorUrl">The URL of the author's website or profile.</param>
  /// <returns>A string containing the generated code header.</returns>
  public static string GetCodeHeader(string authorName, string authorUrl)
  {
    return $$"""
           //------------------------------------------------------------------------------
           // <auto-generated>
           // This code was generated by {{authorName}}
           // {{authorUrl}}
           // <auto-generated />
           //------------------------------------------------------------------------------
           #nullable enable
           """;
  }
}